    public static String formatShortFileSize(android.content.Context c, long n) { return c == null ? "" : fmt(n, FLAG_SI_UNITS | FLAG_SHORTER); }
    /*
     * A size as Android 9's formatBytes words it: the unit the next up once the value is over 900 of it, in thousands (or
     * 1024s with FLAG_IEC_UNITS); no decimals for bytes or for a value of 100 and more, two below 1, and from 1 to 100 two
     * as well, or with FLAG_SHORTER one below 10 and none above. LibChecker shows each app's size so ("12.35 MB"); the value
     * from 10 to 100 had one decimal here, and a value of exactly 900 went up a unit.
     */
    private static String fmt(long n, int flags) {
        String[] u = { "B", "kB", "MB", "GB", "TB", "PB" };
        int base = (flags & FLAG_IEC_UNITS) != 0 ? 1024 : 1000;
        double v = Math.abs((double) n);
        int i = 0;
        while (v > 900 && i < u.length - 1) { v /= base; i++; }
        boolean shorter = (flags & FLAG_SHORTER) != 0;
        String format = i == 0 || v >= 100 ? "%.0f" : v < 1 ? "%.2f" : v < 10 ? (shorter ? "%.1f" : "%.2f") : shorter ? "%.0f" : "%.2f";
        return String.format(format, n < 0 ? -v : v) + " " + u[i];
    }
