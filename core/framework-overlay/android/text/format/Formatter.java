    public static android.text.format.Formatter.BytesResult formatBytes(android.content.res.Resources p0, long p1, int p2) {
        String whole = fmt(p1, p2);
        int space = whole.lastIndexOf(' ');
        return new BytesResult(whole.substring(0, space), whole.substring(space + 1), p1);
    }
