    public static java.lang.String formatShortElapsedTime(android.content.Context p0, long p1) {
        long s = p1 / 1000, d = s / 86400, h = s / 3600 % 24, m = s / 60 % 60;
        return d > 0 ? d + " d" : h > 0 ? h + " h" : m > 0 ? m + " min" : s % 60 + " s";
    }
    /** As Android's: the time in whole minutes, a part of one counted as one; none or one said as minutes. */
    public static java.lang.String formatShortElapsedTimeRoundingUpToMinutes(android.content.Context p0, long p1) {
        long minutes = (p1 + 59999) / 60000;
        return minutes <= 1 ? minutes + " min" : formatShortElapsedTime(p0, minutes * 60000);
    }
