package android.app;

/** The hidden AppGlobals: the process's Application and package name. */
public class AppGlobals {
    public static Application getInitialApplication() { return ActivityThread.currentApplication(); }
    public static String getInitialPackage() { return ActivityThread.currentPackageName(); }
    /** The package manager's hidden interface: for an app of the platform's own, megler.PlatformInterfaces'; null for any other. */
    public static android.content.pm.IPackageManager getPackageManager() {
        return (android.content.pm.IPackageManager) megler.PlatformInterfaces.service("package");
    }
    // ---- generated by tools/compat/fillmembers.py: the platform's members this class does not write (signatures only)
    public static float getFloatCoreSetting(java.lang.String p0, float p1) { return 0f; }
    public static int getIntCoreSetting(java.lang.String p0, int p1) { return 0; }
    public static int getIntCoreSetting(java.lang.String p0, int p1, int p2) { return 0; }
    // ---- end of generated members
}
