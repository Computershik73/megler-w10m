    /** The headers of a preference-headers XML file: each header's own attributes, its extras (the fragment's arguments) and its intent. */
    public void loadHeadersFromResource(int resId, java.util.List<Header> target) {
        final String ns = "http://schemas.android.com/apk/res/android";
        android.content.res.XmlResourceParser p = null;
        try {
            p = getResources().getXml(resId);
            android.util.AttributeSet attrs = android.util.Xml.asAttributeSet(p);
            Header cur = null;
            for (int type = p.next(); type != org.xmlpull.v1.XmlPullParser.END_DOCUMENT; type = p.next()) {
                String tag = p.getName();
                if (type == org.xmlpull.v1.XmlPullParser.END_TAG && "header".equals(tag)) cur = null;
                if (type != org.xmlpull.v1.XmlPullParser.START_TAG) continue;
                if ("header".equals(tag)) {
                    cur = new Header();
                    android.content.res.TypedArray a = obtainStyledAttributes(attrs, HEADER_ATTRS);
                    cur.iconRes = a.getResourceId(0, 0);
                    cur.id = a.getResourceId(1, (int) HEADER_ID_UNDEFINED);
                    cur.titleRes = a.getResourceId(2, 0);
                    if (cur.titleRes == 0) cur.title = a.getText(2);
                    cur.summaryRes = a.getResourceId(3, 0);
                    if (cur.summaryRes == 0) cur.summary = a.getText(3);
                    cur.fragment = a.getString(4);
                    a.recycle();
                    target.add(cur);
                } else if (cur != null && "extra".equals(tag)) {
                    String name = p.getAttributeValue(ns, "name"), value = p.getAttributeValue(ns, "value");
                    if (name != null) {
                        if (cur.fragmentArguments == null) cur.fragmentArguments = new Bundle();
                        cur.fragmentArguments.putString(name, value);
                    }
                } else if (cur != null && "intent".equals(tag)) {
                    String action = p.getAttributeValue(ns, "action"), cls = p.getAttributeValue(ns, "targetClass"), pkg = p.getAttributeValue(ns, "targetPackage"),
                           data = p.getAttributeValue(ns, "data");
                    cur.intent = new android.content.Intent();
                    if (action != null) cur.intent.setAction(action);
                    if (data != null) cur.intent.setData(android.net.Uri.parse(data));
                    if (cls != null) cur.intent.setClassName(pkg != null ? pkg : getPackageName(), cls);
                }
            }
        } catch (Exception e) {
            throw new RuntimeException("Error parsing headers", e);
        } finally {
            if (p != null) p.close();
        }
    }
