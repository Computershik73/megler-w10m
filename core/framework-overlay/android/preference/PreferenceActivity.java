    /** A header was touched: on one pane, its fragment in an activity of its own, or its intent. */
    public void onHeaderClick(Header header, int position) {
        if (header.fragment != null) startWithFragment(header.fragment, header.fragmentArguments, null, 0, header.titleRes, header.breadCrumbShortTitleRes);
        else if (header.intent != null) startActivity(header.intent);
    }
    public android.content.Intent onBuildStartFragmentIntent(String fragmentName, Bundle args, int titleRes, int shortTitleRes) {
        android.content.Intent i = new android.content.Intent(android.content.Intent.ACTION_MAIN);
        i.setClass(this, getClass());
        i.putExtra(EXTRA_SHOW_FRAGMENT, fragmentName);
        i.putExtra(EXTRA_SHOW_FRAGMENT_ARGUMENTS, args);
        i.putExtra(EXTRA_SHOW_FRAGMENT_TITLE, titleRes);
        i.putExtra(EXTRA_SHOW_FRAGMENT_SHORT_TITLE, shortTitleRes);
        i.putExtra(EXTRA_NO_HEADERS, true);
        return i;
    }
    public void startWithFragment(String fragmentName, Bundle args, android.app.Fragment resultTo, int resultRequestCode) { startWithFragment(fragmentName, args, resultTo, resultRequestCode, 0, 0); }
    public void startWithFragment(String fragmentName, Bundle args, android.app.Fragment resultTo, int resultRequestCode, int titleRes, int shortTitleRes) {
        startActivity(onBuildStartFragmentIntent(fragmentName, args, titleRes, shortTitleRes));
    }
    public void switchToHeader(Header header) { if (header != null && header.fragment != null) switchToHeader(header.fragment, header.fragmentArguments); }
    /** The fragment takes the place of the headers' list, inside the root: whatever the app put above the list (a toolbar) stays. */
    private int meglerFragmentFrame() {
        if (mPrefsFrame == null) return android.R.id.content;
        mHeadersColumn.setVisibility(View.GONE);
        mPrefsFrame.setVisibility(View.VISIBLE);
        return mPrefsFrame.getId();
    }
