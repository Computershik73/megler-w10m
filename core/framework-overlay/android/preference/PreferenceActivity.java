    /** Android's preference_list_content, as far as its shape goes: root (vertical) > row (horizontal) > headers (vertical) > android:id/list, and the fragment's frame beside the headers. */
    private View meglerContent() {
        android.widget.LinearLayout root = new android.widget.LinearLayout(this), row = new android.widget.LinearLayout(this), headers = new android.widget.LinearLayout(this);
        root.setOrientation(android.widget.LinearLayout.VERTICAL);
        row.setOrientation(android.widget.LinearLayout.HORIZONTAL);
        headers.setOrientation(android.widget.LinearLayout.VERTICAL);
        ListView list = new ListView(this);
        list.setId(android.R.id.list);
        headers.addView(list, new android.widget.LinearLayout.LayoutParams(android.view.ViewGroup.LayoutParams.MATCH_PARENT, 0, 1f));
        mHeadersColumn = headers;
        mPrefsFrame = new android.widget.FrameLayout(this);
        int prefs = getResources().getIdentifier("prefs", "id", "android");
        mPrefsFrame.setId(prefs != 0 ? prefs : View.generateViewId());
        mPrefsFrame.setVisibility(View.GONE);
        row.addView(headers, new android.widget.LinearLayout.LayoutParams(0, android.view.ViewGroup.LayoutParams.MATCH_PARENT, 1f));
        row.addView(mPrefsFrame, new android.widget.LinearLayout.LayoutParams(0, android.view.ViewGroup.LayoutParams.MATCH_PARENT, 1f));
        root.addView(row, new android.widget.LinearLayout.LayoutParams(android.view.ViewGroup.LayoutParams.MATCH_PARENT, 0, 1f));
        return root;
    }
    @Override protected void onCreate(Bundle state) {
        super.onCreate(state);
        setContentView(meglerContent(), new android.view.ViewGroup.LayoutParams(android.view.ViewGroup.LayoutParams.MATCH_PARENT, android.view.ViewGroup.LayoutParams.MATCH_PARENT));
        mManager = new PreferenceManager(this, 100);
        mManager.meglerSetTreeClickListener(this);
        android.content.Intent in = getIntent();
        String frag = in != null ? in.getStringExtra(EXTRA_SHOW_FRAGMENT) : null;
        if (frag != null) {
            /* One header's screen, started by a touch of that header (startWithFragment): its fragment, under its title. */
            int title = in.getIntExtra(EXTRA_SHOW_FRAGMENT_TITLE, 0);
            if (title != 0) setTitle(title);
            switchToHeader(frag, in.getBundleExtra(EXTRA_SHOW_FRAGMENT_ARGUMENTS));
            return;
        }
        if (in == null || !in.getBooleanExtra(EXTRA_NO_HEADERS, false)) {
            onBuildHeaders(mHeaders);
            if (!mHeaders.isEmpty()) meglerShowHeaders();
        }
    }
    private void meglerShowHeaders() {
        mShowingHeaders = true;
        setListAdapter(new android.widget.BaseAdapter() {
            @Override public int getCount() { return mHeaders.size(); }
            @Override public Object getItem(int position) { return mHeaders.get(position); }
            @Override public long getItemId(int position) { return position; }
            @Override public View getView(int position, View row, android.view.ViewGroup parent) {
                if (row == null) {
                    /* The platform's own row for a header, where its resources are there: an icon, a title, a summary. */
                    int layout = getResources().getIdentifier("preference_header_item", "layout", "android");
                    row = getLayoutInflater().inflate(layout != 0 ? layout : android.R.layout.simple_list_item_2, parent, false);
                }
                Header h = mHeaders.get(position);
                View title = row.findViewById(android.R.id.title), summary = row.findViewById(android.R.id.summary), icon = row.findViewById(android.R.id.icon);
                if (title == null) title = row.findViewById(android.R.id.text1);
                if (summary == null) summary = row.findViewById(android.R.id.text2);
                CharSequence s = h.getSummary(getResources());
                if (title instanceof android.widget.TextView) ((android.widget.TextView) title).setText(h.getTitle(getResources()));
                if (summary instanceof android.widget.TextView) {
                    ((android.widget.TextView) summary).setText(s);
                    summary.setVisibility(s == null || s.length() == 0 ? View.GONE : View.VISIBLE);
                }
                if (icon instanceof android.widget.ImageView) {
                    if (h.iconRes != 0) ((android.widget.ImageView) icon).setImageResource(h.iconRes);
                    else ((android.widget.ImageView) icon).setImageDrawable(null);
                }
                return row;
            }
        });
    }
