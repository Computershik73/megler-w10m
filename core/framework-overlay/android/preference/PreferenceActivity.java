// megler-w10m overlay of Megler/src/java-framework/src/android/preference/PreferenceActivity.java (tools/build-framework.sh).
// It differs in two things: the activity's content, set in onCreate as Android sets it; and preference headers, which are
// read, listed and opened here, where the original showed the first header's fragment and nothing else.
//
// The content. Android's PreferenceActivity.onCreate calls setContentView with the platform's preference_list_content
// layout, so from onCreate on the activity has a ListView with the id android.R.id.list, three layouts deep: a vertical
// LinearLayout (the root), a horizontal one in it, a vertical one (the headers' column) in that, and the list in the
// column; beside the column, a frame for a header's fragment. The original makes its list only when something asks for it
// (ListActivity.getListView), as the bare content view. An app that never asks has no list at all, and one that looks for
// the list's ancestors does not find Android's. The usual way to give a PreferenceActivity a toolbar is
//     LinearLayout root = (LinearLayout) findViewById(android.R.id.list).getParent().getParent().getParent();
//     root.addView(toolbar, 0);
// in onPostCreate. Apktool M's settings screen does exactly that, got null from findViewById, and ended the app with
// "NullPointerException: ... View.getParent() on a null object reference (in SettingActivity.onPostCreate)". The layout is
// made in code (meglerContent), with Android's shape and none of its paddings.
//
// The headers. A settings screen written for Android 3 to 9 is a list of headers (onBuildHeaders, usually
// loadHeadersFromResource), each of which opens a PreferenceFragment. loadHeadersFromResource was an empty method here, so
// such a screen was an empty list -- Apktool M's again, once it no longer ended the app. Now the XML is read (header: id,
// title, summary, icon, fragment; its extra and intent children), the list shows the headers in the platform's own row
// layout, and a touch does what Android does on a phone, where there is one pane: onHeaderClick starts this same activity
// again with EXTRA_SHOW_FRAGMENT, and that instance shows the fragment in the frame instead of the list. An intent header
// starts its intent. Not done: two panes side by side (onIsMultiPane is false), bread crumbs, the list footer and the
// "next" button of a setup wizard. Everything else is the original's, unchanged.
