// Overlay of core/framework/src/android/graphics/drawable/RippleDrawable.java (tools/build-framework.sh).
// It differs by one method, meglerSetMask, through which the inflater says that the ripple has a mask (megler/ResInflate.java,
// also in the overlay). Everything else is the original's, unchanged.
//
// Why. Android's commonest ripple is one with nothing in it but a mask -- item_background_material, which is
// ?attr/selectableItemBackground and the selector of every ListView: <ripple><item android:id="@android:id/mask">...</item>
// </ripple>. The mask is not drawn; it says where the ripple may show, which for these is the view's own rectangle. The
// original's inflater leaves the mask layer out, rightly, but never tells the RippleDrawable it had one. With no mask and
// no layers the drawable takes itself for an unbounded ripple (a borderless icon button's) and draws its highlight as a
// disc of half its longer side round its middle: for a pressed row of a list, a grey disc as wide as the screen over the
// rows above and below it.
package android.graphics.drawable;

import android.content.res.ColorStateList;
import android.graphics.*;

/** The content layers, with a light press highlight in the ripple's colour while pressed. */
public class RippleDrawable extends LayerDrawable {
    public static final int RADIUS_AUTO = -1;
    private ColorStateList mColor;
    private boolean mPressed;
    private final Paint mPaint = new Paint(Paint.ANTI_ALIAS_FLAG);
    private Drawable mMask;
    public RippleDrawable(ColorStateList color, Drawable content, Drawable mask) {
        super(content != null ? new Drawable[] { content } : new Drawable[0]);
        mColor = color; mMask = mask;
    }
    /** megler-w10m: the mask layer of a ripple inflated from XML, which bounds it. See the top of the file. */
    public void meglerSetMask(Drawable mask) { mMask = mask; }
    public void setColor(ColorStateList c) { mColor = c; invalidateSelf(); }
    public void setRadius(int r) {}
    public int getRadius() { return RADIUS_AUTO; }
    public void setEffectColor(ColorStateList c) {}
    @Override public boolean isStateful() { return true; }
    @Override protected boolean onStateChange(int[] s) {
        super.onStateChange(s);
        boolean p = false, en = true;
        for (int v : s) { if (v == android.R.attr.state_pressed) p = true; }
        if (p != mPressed) { mPressed = p; invalidateSelf(); return true; }
        return false;
    }
    @Override public void draw(Canvas c) {
        super.draw(c);
        if (mPressed && mColor != null) {
            int col = mColor.getDefaultColor();
            mPaint.setColor((col & 0xFFFFFF) | (Math.min(0x40, col >>> 24) << 24));
            Rect b = getBounds();
            if (mMask != null || getNumberOfLayers() > 0) c.drawRect(b, mPaint);
            else c.drawCircle(b.exactCenterX(), b.exactCenterY(), Math.max(b.width(), b.height()) / 2f, mPaint);
        }
    }
    // ---- generated by tools/compat/fillmembers.py: the platform's members this class does not write (signatures only)
    public static final int STYLE_PATTERNED = 1;
    public static final int STYLE_SOLID = 0;
    public android.content.res.ColorStateList getEffectColor() { return null; }
    public float getTargetBackgroundOpacity() { return 0f; }
    public boolean isProjected() { return false; }
    public void setBackgroundActive(boolean p0, boolean p1, boolean p2, boolean p3) {}
    public void setForceSoftware(boolean p0) {}
    // ---- end of generated members
}
