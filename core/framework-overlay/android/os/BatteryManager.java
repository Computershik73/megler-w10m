    /** As Android means it: on power, and the charge going up or full. */
    public boolean isCharging() {
        int[] s = megler.Native.battery();
        return s[3] != 0 && (s[2] == BATTERY_STATUS_CHARGING || s[2] == BATTERY_STATUS_FULL);
    }
