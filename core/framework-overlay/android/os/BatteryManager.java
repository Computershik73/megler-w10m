    public int getIntProperty(int id) {
        int[] s = megler.Native.battery();
        return id == BATTERY_PROPERTY_CAPACITY ? (s[1] > 0 ? s[0] * 100 / s[1] : 0) : id == BATTERY_PROPERTY_STATUS ? s[2] : 0;
    }
