    /*
     * The alarms of this process, by their PendingIntent, as Android keeps them: one each, which a new one with the same
     * PendingIntent replaces (PendingIntent finds the same one again for the same intent), which cancel takes away, as it does
     * the PendingIntent's cancel (meglerCanceled), and a repeating one goes off again each interval. Every AlarmManager of the
     * process has them alike.
     */
    private static final java.util.IdentityHashMap<PendingIntent, Runnable> sAlarms = new java.util.IdentityHashMap<>();
    private static android.os.Handler sAlarmHandler;
    private static void schedule(PendingIntent op, long delay, long interval) {
        if (op == null) return;
        Runnable fire = new Runnable() {
            @Override public void run() {
                synchronized (sAlarms) {
                    if (sAlarms.get(op) != this) return;
                    if (interval <= 0) sAlarms.remove(op);
                }
                said(what(op), false, 0, 0, null);
                try { op.send(); } catch (PendingIntent.CanceledException e) { synchronized (sAlarms) { if (sAlarms.get(op) == this) sAlarms.remove(op); } return; }
                synchronized (sAlarms) { if (interval > 0 && sAlarms.get(op) == this) sAlarmHandler.postDelayed(this, op, interval); }
            }
        };
        synchronized (sAlarms) {
            if (sAlarmHandler == null) sAlarmHandler = new android.os.Handler(android.os.Looper.getMainLooper());
            sAlarmHandler.removeCallbacksAndMessages(op);
            sAlarms.put(op, fire);
            sAlarmHandler.postDelayed(fire, op, delay);
        }
        said(what(op), true, delay, interval, "a PendingIntent's");
    }
    /** PendingIntent.cancel: its alarm, if it has one, goes. */
    public static void meglerCanceled(PendingIntent op) {
        synchronized (sAlarms) {
            if (sAlarms.remove(op) != null && sAlarmHandler != null) sAlarmHandler.removeCallbacksAndMessages(op);
        }
    }
    private static String what(PendingIntent op) {
        android.content.Intent i = op.meglerIntent();
        return i == null ? "a PendingIntent" : i.getAction() != null ? i.getAction() : i.getComponent() != null ? i.getComponent().getClassName() : "a PendingIntent";
    }

    /*
     * The alarms of a listener (Android 7's OnAlarmListener, and the forms with an Executor and a WorkSource that Google Play
     * services' alarms are set with, GmsAlarm: their network location's next scan and fix among them), as Android keeps them:
     * one for each listener, which a new one for the same listener replaces and cancel(listener) takes away, told on the
     * Handler given (the main thread's without one) or through the Executor given, and a repeating one again each interval.
     * Only PendingIntent's forms and set(..., OnAlarmListener, Handler) went off before; the others were signatures that did
     * nothing, and an alarm of Google Play services' never went off: their network location scanned the Wi-Fi once and was
     * never run again. They are timed on a thread of their own ("AlarmManager"), so that a busy main thread does not hold
     * up those told elsewhere. A window's alarm goes off at its start.
     */
    private static final class Listened implements Runnable {
        final OnAlarmListener listener;
        final android.os.Handler handler;
        final java.util.concurrent.Executor executor;
        final long interval;
        final String tag;
        Listened(OnAlarmListener l, android.os.Handler h, java.util.concurrent.Executor e, long interval, String tag) {
            listener = l; handler = h; executor = e; this.interval = interval; this.tag = tag;
        }
        @Override public void run() {
            synchronized (sListened) {
                if (sListened.get(listener) != this) return;
                if (interval <= 0) {
                    sListened.remove(listener);
                    sTelling.put(listener, this);
                } else {
                    sTimer.postDelayed(this, interval);
                }
            }
            said(tag, false, 0, 0, null);
            // (Told unless it was cancelled meanwhile: a repeating one while it is still the listener's, one that went off
            // once while it is the one going off -- not set again and gone off again before it was told.)
            Runnable tell = () -> {
                synchronized (sListened) {
                    if (interval > 0) {
                        if (sListened.get(listener) != this) return;
                    } else {
                        if (sTelling.get(listener) != this) return;
                        sTelling.remove(listener);
                    }
                }
                listener.onAlarm();
            };
            if (executor != null) executor.execute(tell);
            else (handler != null ? handler : main()).post(tell);
        }
    }
    /* The listeners' alarms not yet gone off, and those gone off and not yet told (which cancel stops too). */
    private static final java.util.IdentityHashMap<OnAlarmListener, Listened> sListened = new java.util.IdentityHashMap<>(), sTelling = new java.util.IdentityHashMap<>();
