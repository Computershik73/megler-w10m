package android.os;

/**
 * A thread with a looper, as Android's. getLooper of a thread not started, or ended, is null at once, as there: it waited for a
 * looper that would never come, and Facebook's stories loader stood in it for the whole run, the app showing its loading
 * circles. It says so in the log, with the thread's name.
 */
public class HandlerThread extends Thread {
    int mPriority;
    int mTid = -1;
    Looper mLooper;
    private Handler mHandler;

    public HandlerThread(String name) { super(name); mPriority = Process.THREAD_PRIORITY_DEFAULT; }
    public HandlerThread(String name, int priority) { super(name); mPriority = priority; }
    protected void onLooperPrepared() {}
    @Override public void run() {
        mTid = Process.myTid();
        Looper.prepare();
        synchronized (this) { mLooper = Looper.myLooper(); notifyAll(); }
        Process.setThreadPriority(mPriority);
        onLooperPrepared();
        Looper.loop();
        mTid = -1;
    }
    public Looper getLooper() {
        if (!isAlive()) {
            if (mLooper == null) android.util.Log.w("Megler", "HandlerThread \"" + getName() + "\": getLooper of a thread " + (getState() == State.NEW ? "not started" : "that ended") + ": null");
            return null;
        }
        boolean interrupted = false;
        synchronized (this) {
            while (isAlive() && mLooper == null) {
                try { wait(); } catch (InterruptedException e) { interrupted = true; }
            }
        }
        if (interrupted) Thread.currentThread().interrupt();
        return mLooper;
    }
    public Handler getThreadHandler() {
        if (mHandler == null) mHandler = new Handler(getLooper());
        return mHandler;
    }
    public boolean quit() { Looper l = getLooper(); if (l != null) l.quit(); return l != null; }
    public boolean quitSafely() { Looper l = getLooper(); if (l != null) l.quitSafely(); return l != null; }
    public int getThreadId() { return mTid; }
    // ---- generated by tools/compat/fillmembers.py: the platform's members this class does not write (signatures only)
    public java.util.concurrent.Executor getThreadExecutor() { return null; }
    protected void onCreated() {}
    // ---- end of generated members
}
