r"""Android 9's hidden methods that an app of the platform's own names on Megler's framework classes, and that those classes lack:
generated for them, each answering as a phone without what it is about would (false, 0, null, an empty array or list).

    python tools/compat/platform-members.py APK [--write]

An app of the platform's own (Android's Settings, AOSP 9, which Megler's package carries: build/android9/apps/
android-settings.apk) has Android 9's framework after Megler's (drivers/mg_java.c, add_platform_framework), so a class Megler's
framework has is Megler's, and a hidden method of Android 9's that Megler's class lacks is a NoSuchMethodError where the app
calls it: Settings' Connected devices ended on UsbManager.getPorts()[Landroid/hardware/usb/UsbPort;, its Display on
PowerManager.getMinimumScreenBrightnessForVrSetting, its Storage on StorageManager.registerListener.

This reads the app's DEX files, Megler's framework (build/framework/megler-framework*.dex), the Android root's libcore and
Android 9's framework (build/android9/boot), and looks up every method the app's code names on a class of Megler's framework
as the runtime would (the class, its superclasses, its interfaces). For each that is not there, Android 9's own declaration
(static or not) gives the member to add, between the markers tools/list-stubs.py knows ("generated by
tools/compat/fillmembers.py" ... "end of generated members"), so that the runtime says its first call ("api: ... is a stub
here"): in core/framework-overlay/<class>.java.members, after any members written there by hand. Left out, and listed: a
method of an interface (its implementations would lack it), a constructor, one whose name and parameters Megler's class has
with another return type (Java cannot declare both), and one that names a class the framework cannot be compiled against.
Without --write it only says what it would add.
"""
import os
import struct
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BEGIN = "    // ---- generated by tools/compat/fillmembers.py: Android 9's hidden members an app of the platform's own names (tools/compat/platform-members.py)"
END = "    // ---- end of generated members"
ACC_STATIC, ACC_INTERFACE = 0x8, 0x200


def uleb(b, o):
    r = s = 0
    while True:
        x = b[o]
        o += 1
        r |= (x & 0x7f) << s
        s += 7
        if x < 0x80:
            return r, o


class Dex:
    """A DEX file's names, references and classes: for each class its super, interfaces, flags, methods (name, descriptor) ->
    access flags."""
    def __init__(self, data):
        b = data
        sz = lambda off: struct.unpack_from('<II', b, off)
        n_str, o_str = sz(0x38); n_typ, o_typ = sz(0x40); n_pro, o_pro = sz(0x48)
        n_fld, o_fld = sz(0x50); n_met, o_met = sz(0x58); n_cls, o_cls = sz(0x60)
        strs = []
        for i in range(n_str):
            so = struct.unpack_from('<I', b, o_str + 4 * i)[0]
            _, so = uleb(b, so)
            strs.append(b[so:b.index(b'\0', so)].decode('utf-8', 'replace'))
        types = [strs[struct.unpack_from('<I', b, o_typ + 4 * i)[0]] for i in range(n_typ)]
        protos = []
        for i in range(n_pro):
            _, ret, par = struct.unpack_from('<III', b, o_pro + 12 * i)
            ps = []
            if par:
                n = struct.unpack_from('<I', b, par)[0]
                ps = [types[struct.unpack_from('<H', b, par + 4 + 2 * k)[0]] for k in range(n)]
            protos.append('(' + ''.join(ps) + ')' + types[ret])
        self.methods = []
        for i in range(n_met):
            c, p, n = struct.unpack_from('<HHI', b, o_met + 8 * i)
            self.methods.append((types[c], strs[n], protos[p]))
        self.classes = {}
        for i in range(n_cls):
            ci, acc, sup, ifs, _, _, data_off, _ = struct.unpack_from('<8I', b, o_cls + 32 * i)
            ifaces = []
            if ifs:
                n = struct.unpack_from('<I', b, ifs)[0]
                ifaces = [types[struct.unpack_from('<H', b, ifs + 4 + 2 * k)[0]] for k in range(n)]
            ms = {}
            if data_off:
                o = data_off
                a, o = uleb(b, o); bb, o = uleb(b, o); c, o = uleb(b, o); d, o = uleb(b, o)
                for _ in range(a + bb):
                    _, o = uleb(b, o); _, o = uleb(b, o)
                for cnt in (c, d):
                    idx = 0
                    for _ in range(cnt):
                        diff, o = uleb(b, o)
                        idx += diff
                        flags, o = uleb(b, o)
                        _, o = uleb(b, o)
                        ms[self.methods[idx][1:]] = flags
            self.classes[types[ci]] = (types[sup] if sup != 0xffffffff else None, ifaces, acc, ms)


def dexes_of(path):
    if path.endswith('.dex'):
        return [Dex(open(path, 'rb').read())]
    with zipfile.ZipFile(path) as z:
        return [Dex(z.read(n)) for n in sorted(z.namelist()) if n.startswith('classes') and n.endswith('.dex')]


def java_type(desc):
    dims = 0
    while desc[dims] == '[':
        dims += 1
    base = desc[dims:]
    prim = {'Z': 'boolean', 'B': 'byte', 'C': 'char', 'S': 'short', 'I': 'int', 'J': 'long', 'F': 'float', 'D': 'double', 'V': 'void'}
    name = prim.get(base) or base[1:-1].replace('/', '.').replace('$', '.')
    return name + '[]' * dims


def split_params(sig):
    params, i, body = [], 0, sig[1:sig.index(')')]
    while i < len(body):
        j = i
        while body[j] == '[':
            j += 1
        j = body.index(';', j) + 1 if body[j] == 'L' else j + 1
        params.append(body[i:j])
        i = j
    return params, sig[sig.index(')') + 1:]


def default_body(ret):
    if ret == 'V':
        return '{}'
    if ret == 'Z':
        return '{ return false; }'
    if ret in ('B', 'C', 'S', 'I', 'J', 'F', 'D'):
        return '{ return 0; }'
    if ret.startswith('['):
        dims = len(ret) - len(ret.lstrip('['))
        return '{ return new %s[0]%s; }' % (java_type(ret.lstrip('[')), '[]' * (dims - 1))
    if ret in ('Ljava/util/List;', 'Ljava/util/Collection;', 'Ljava/lang/Iterable;'):
        return '{ return new java.util.ArrayList(); }'
    if ret == 'Ljava/util/Set;':
        return '{ return new java.util.HashSet(); }'
    if ret == 'Ljava/util/Map;':
        return '{ return new java.util.HashMap(); }'
    return '{ return null; }'


def main():
    apk = sys.argv[1]
    write = '--write' in sys.argv[2:]
    boot_dir = os.path.join(ROOT, 'build', 'android9', 'boot')
    root_fw = os.path.join(ROOT, 'build', 'android9', 'root', 'framework')
    fw_dir = os.path.join(ROOT, 'build', 'framework')
    libcore = [os.path.join(root_fw, n) for n in ('megler-libcore.dex', 'core-oj.dex', 'core-libart.dex', 'conscrypt.dex', 'okhttp.dex',
                                                  'bouncycastle.dex', 'apache-xml.dex')]
    megler = sorted(os.path.join(fw_dir, n) for n in os.listdir(fw_dir) if n.startswith('megler-framework') and n.endswith('.dex'))
    platform = [os.path.join(boot_dir, n) for n in ('framework.dex', 'framework-classes2.dex', 'framework-classes3.dex',
                                                    'telephony-common.dex', 'ims-common.dex')]
    owner = {}
    for group, paths in (('boot', libcore), ('megler', megler), ('platform', platform)):
        for p in paths:
            for d in dexes_of(p):
                for name, c in d.classes.items():
                    owner.setdefault(name, (group, c))
    platform_defs = {}
    for p in platform:
        for d in dexes_of(p):
            for name, c in d.classes.items():
                platform_defs.setdefault(name, c)
    app = dexes_of(apk)
    own = set()
    for d in app:
        own.update(d.classes)

    def find(cls, member, seen):
        while cls and cls not in seen:
            seen.add(cls)
            o = owner.get(cls)
            if not o:
                return None
            if member in o[1][3]:
                return o[0]
            for i in o[1][1]:
                r = find(i, member, seen)
                if r:
                    return r
            cls = o[1][0]
        return None

    def platform_flags(cls, member):
        while cls:
            c = platform_defs.get(cls)
            if not c:
                return None
            if member in c[3]:
                return c[3][member]
            cls = c[0]
        return None

    stubs_dir = os.path.join(ROOT, 'core', 'framework', 'stubs')

    def compilable(desc):
        # A class of libcore's or Megler's framework, or one declared for compiling alone (core/framework/stubs).
        base = desc.lstrip('[')
        if not base.startswith('L') or (base in owner and owner[base][0] in ('boot', 'megler')):
            return True
        return os.path.isfile(os.path.join(stubs_dir, *base[1:-1].split('$')[0].split('/')) + '.java') and '$' not in base

    add, skipped = {}, []
    for d in app:
        for cls, name, sig in d.methods:
            base = cls.lstrip('[')
            if base in own or base not in owner or owner[base][0] != 'megler':
                continue
            if find(base, (name, sig), set()):
                continue
            flags = platform_flags(base, (name, sig))
            why = None
            params, ret = split_params(sig)
            if name == '<init>':
                why = 'a constructor'
            elif owner[base][1][2] & ACC_INTERFACE:
                why = 'a method of an interface'
            elif flags is None:
                why = "not Android 9's"
            elif any(m == name and split_params(s)[0] == params for m, s in owner[base][1][3]):
                why = 'declared with another return type'
            elif not all(compilable(t) for t in params + [ret]):
                why = 'names a class the framework is not compiled against: ' + ', '.join(t for t in params + [ret] if not compilable(t))
            if why:
                skipped.append('%s.%s%s: %s' % (base[1:-1], name, sig, why))
                continue
            decl = '    public %s%s %s(%s) %s' % ('static ' if flags & ACC_STATIC else '', java_type(ret), name,
                                               ', '.join('%s p%d' % (java_type(t), k) for k, t in enumerate(params)), default_body(ret))
            add.setdefault(base[1:-1], {})[name + sig] = decl
    for cls in sorted(add):
        print('%s: %d' % (cls, len(add[cls])))
        for k in sorted(add[cls]):
            print('   ', add[cls][k].strip())
    print('left out: %d' % len(sorted(set(skipped))))
    for s in sorted(set(skipped)):
        print('   ', s)
    if not write:
        return
    for cls, members in add.items():
        path = os.path.join(ROOT, 'core', 'framework-overlay', cls.replace('/', os.sep).split('$')[0] + '.java.members')
        if '$' in cls:
            print('nested class, not written: ' + cls)
            continue
        text = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
        if BEGIN in text:
            text = text[:text.index(BEGIN)].rstrip('\n') + '\n' if text.index(BEGIN) else ''
        block = BEGIN + '\n' + '\n'.join(members[k] for k in sorted(members)) + '\n' + END + '\n'
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write((text + block) if text else block)
    print('written')


main()
