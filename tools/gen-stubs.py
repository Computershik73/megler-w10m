"""Turns the assembled stubs (a flat binary and nm's symbol list) into mg_stubs_blob.h."""
import sys


def main():
    bin_path, nm_path, out_path = sys.argv[1:4]
    data = open(bin_path, 'rb').read()
    symbols = []
    for line in open(nm_path):
        parts = line.split()
        if len(parts) == 3 and parts[2].startswith('mg_'):
            # A Thumb function's symbol value has the low bit set in nm's output only with
            # --synthetic; here it is the plain address, and mg_stubs.c adds the bit itself.
            symbols.append((parts[2], int(parts[0], 16)))
    symbols.sort(key=lambda s: s[1])
    out = []
    out.append('/* Generated by tools/gen-stubs.sh from mg_stubs.S. Do not edit. */')
    out.append('#ifndef MG_STUBS_BLOB_H')
    out.append('#define MG_STUBS_BLOB_H')
    out.append('')
    for name, value in symbols:
        out.append('#define %s_OFFSET 0x%X' % (name.upper(), value))
    out.append('')
    out.append('static const unsigned char mg_stubs_blob[%d] = {' % len(data))
    for i in range(0, len(data), 16):
        out.append('    ' + ' '.join('0x%02X,' % b for b in data[i:i + 16]))
    out.append('};')
    out.append('')
    out.append('#endif')
    open(out_path, 'w', newline='\n').write('\n'.join(out) + '\n')


main()
