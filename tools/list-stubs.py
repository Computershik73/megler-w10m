"""The framework's methods that are signatures alone: what tools/build-framework.sh writes to megler-stubs.txt.

    python tools/list-stubs.py <classes dir> <sources.txt> <core/framework> <core/framework-overlay> <out>

A method is one when its body is generated, not written: every method of a class of core/framework/gen-src (the
platform's classes made from Android 14's framework.jar with signatures and constants only), and every method between
the markers "---- generated by tools/compat/fillmembers.py" and "---- end of generated members" in a class that is
written (the platform's members it does not write) -- each generated on one line, its signature and body together; a
member written in a generated one's place spans lines, or says @Override on its one line, and is not one. A getter or
setter of a generated class that keeps what it is given (meglerProps) is not one either: it does what Android's does
with a value. Constructors are left out:
an object made is not what fails, its methods are. Which source line a method's body is on comes
from the class file's line numbers (javac), so its descriptor is exactly the one the runtime links.

One line a method, sorted: "<class> <name> <descriptor>" ("android/app/Fragment getLayoutInflater
()Landroid/view/LayoutInflater;"). The runtime (mg_dvm_class.c) marks those methods and says the first call of each in
the log (megler: "api: ... is a stub here").
"""
import io
import os
import re
import struct
import sys

ACC_BRIDGE, ACC_SYNTHETIC, ACC_ABSTRACT, ACC_NATIVE = 0x40, 0x1000, 0x400, 0x100
# A method whole on one line: its parameters' close, maybe a throws clause, and its body in braces to the line's end.
ONE_LINE = re.compile(r'\)\s*(?:throws [^{]+)?\{(.*)\}\s*(?://.*)?$')


def read_class(data):
    """(this class's name, its SourceFile, [(name, descriptor, flags, first line or None)])."""
    pos = 10
    count = struct.unpack_from('>H', data, 8)[0]
    pool = [None] * count
    i = 1
    while i < count:
        tag = data[pos]
        if tag == 1:
            n = struct.unpack_from('>H', data, pos + 1)[0]
            pool[i] = data[pos + 3:pos + 3 + n].decode('utf-8', 'replace')
            pos += 3 + n
        elif tag in (7, 8, 16, 19, 20):
            pool[i] = ('ref', struct.unpack_from('>H', data, pos + 1)[0])
            pos += 3
        elif tag == 15:
            pos += 4
        elif tag in (3, 4, 9, 10, 11, 12, 17, 18):
            pos += 5
        elif tag in (5, 6):
            pos += 9
            i += 1
        else:
            raise ValueError('constant pool tag %d' % tag)
        i += 1
    utf = lambda k: pool[k] if isinstance(pool[k], str) else None
    this_class = utf(pool[struct.unpack_from('>H', data, pos + 2)[0]][1])
    pos += 6
    ninterfaces = struct.unpack_from('>H', data, pos)[0]
    pos += 2 + 2 * ninterfaces

    def skip_attributes(p):
        n = struct.unpack_from('>H', data, p)[0]
        p += 2
        for _ in range(n):
            p += 6 + struct.unpack_from('>I', data, p + 2)[0]
        return p

    nfields = struct.unpack_from('>H', data, pos)[0]
    pos += 2
    for _ in range(nfields):
        pos = skip_attributes(pos + 6)
    methods = []
    nmethods = struct.unpack_from('>H', data, pos)[0]
    pos += 2
    for _ in range(nmethods):
        flags, name_i, desc_i = struct.unpack_from('>HHH', data, pos)
        pos += 6
        nattrs = struct.unpack_from('>H', data, pos)[0]
        pos += 2
        first = None
        for _ in range(nattrs):
            aname = utf(struct.unpack_from('>H', data, pos)[0])
            alen = struct.unpack_from('>I', data, pos + 2)[0]
            body = pos + 6
            if aname == 'Code':
                code_len = struct.unpack_from('>I', data, body + 4)[0]
                p = body + 8 + code_len
                p += 2 + 8 * struct.unpack_from('>H', data, p)[0]
                n = struct.unpack_from('>H', data, p)[0]
                p += 2
                for _ in range(n):
                    sub = utf(struct.unpack_from('>H', data, p)[0])
                    sublen = struct.unpack_from('>I', data, p + 2)[0]
                    if sub == 'LineNumberTable':
                        lines = [struct.unpack_from('>H', data, p + 8 + 4 * k + 2)[0] for k in range(struct.unpack_from('>H', data, p + 6)[0])]
                        if lines:
                            first = min(lines)
                    p += 6 + sublen
            pos = body + alen
        methods.append((utf(name_i), utf(desc_i), flags, first))
    source = None
    nattrs = struct.unpack_from('>H', data, pos)[0]
    pos += 2
    for _ in range(nattrs):
        aname = utf(struct.unpack_from('>H', data, pos)[0])
        alen = struct.unpack_from('>I', data, pos + 2)[0]
        if aname == 'SourceFile':
            source = utf(struct.unpack_from('>H', data, pos + 6)[0])
        pos += 6 + alen
    return this_class, source, methods


def main():
    classes, sources_txt, framework, overlay, out_path = sys.argv[1:6]
    norm = lambda p: os.path.normcase(os.path.normpath(p))
    gen_src = norm(os.path.join(framework, 'gen-src'))
    members_root = norm(os.path.join(os.path.dirname(classes), 'members'))
    sources = {}
    for line in io.open(sources_txt, encoding='utf-8'):
        path = line.strip()
        if not path:
            continue
        if path[:3].lower() in ('/c/', '/d/'):
            path = path[1] + ':' + path[2:]
        sources[norm(path)] = path
    by_rel = {}
    for key, path in sources.items():
        for root in (norm(os.path.join(framework, 'src')), gen_src, norm(overlay), members_root):
            if key.startswith(root + os.sep):
                by_rel[key[len(root) + 1:]] = path
    ranges_cache = {}

    def ranges(rel):
        """The source's generated lines, as (first, last) pairs, and its text's lines."""
        if rel in ranges_cache:
            return ranges_cache[rel]
        path = by_rel.get(rel)
        result = ([], [])
        if path:
            lines = io.open(path, encoding='utf-8', errors='replace').read().split('\n')
            spans = []
            key = norm(path)
            whole_generated = key.startswith(gen_src + os.sep)
            if key.startswith(members_root + os.sep):
                # A class given more members: generated up to the overlay's part when what it was made from is gen-src's.
                original = os.path.join(framework, 'gen-src', rel)
                written = os.path.join(framework, 'src', rel)
                if os.path.isfile(original) and not os.path.isfile(written) and not os.path.isfile(os.path.join(overlay, rel)):
                    end = next((k for k, l in enumerate(lines) if '---- added by the overlay' in l), len(lines))
                    spans.append((1, end))
            elif whole_generated:
                spans.append((1, len(lines)))
            start = None
            for k, l in enumerate(lines, 1):
                if 'generated by tools/compat/fillmembers.py' in l:
                    start = k
                elif '---- end of generated members' in l and start is not None:
                    spans.append((start, k))
                    start = None
            result = (spans, lines)
        ranges_cache[rel] = result
        return result

    stubs = []
    for dirpath, _, files in os.walk(classes):
        for f in files:
            if not f.endswith('.class'):
                continue
            data = open(os.path.join(dirpath, f), 'rb').read()
            name, source, methods = read_class(data)
            if not name or not source or not (name.startswith('android/') or name.startswith('javax/')):
                continue
            rel = os.path.normcase(os.path.normpath(os.path.join(os.path.dirname(name), source)))
            spans, lines = ranges(rel)
            if not spans:
                continue
            for mname, desc, flags, first in methods:
                if first is None or mname in ('<clinit>', '<init>') or flags & (ACC_BRIDGE | ACC_SYNTHETIC | ACC_ABSTRACT | ACC_NATIVE):
                    continue
                if not any(a <= first <= b for a, b in spans):
                    continue
                # Generated, a member is one line, its signature and body together. One written in a generated block's place
                # (an overlay's real parseIntent, openSession) spans lines, and its first line of code is not its signature's;
                # one written there on one line says @Override, which the generator never wrote (ContextWrapper's broadcasts
                # with options, passed on to the context it wraps, were said to be stubs in every log that sent one).
                text = lines[first - 1] if first - 1 < len(lines) else ''
                body = ONE_LINE.search(text)
                if not body or (mname + '(') not in text or 'meglerProps' in body.group(1) or text.lstrip().startswith('@Override'):
                    continue
                stubs.append('%s %s %s' % (name, mname, desc))
    stubs = sorted(set(stubs))
    io.open(out_path, 'w', encoding='utf-8', newline='\n').write('\n'.join(stubs) + '\n')
    print('framework: %d methods are signatures alone (%s)' % (len(stubs), os.path.basename(out_path)))


main()
