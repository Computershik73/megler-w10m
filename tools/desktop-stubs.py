"""The glue between Megler.exe and the core's ELF on desktop Windows (docs/DESKTOP.md, "The core as an ELF").

    python tools/desktop-stubs.py <megler-core.so> <x64|arm64|x86> <out.c> [llvm-nm]

Reads the core's dynamic symbols and writes one C file for Megler.exe's side (compiled with MG_ELF_HOST):

  - for each function the core exports (megler.h's MEGLER_API ones, mg_log_line, the tests' entries), a stub of that
    name that jumps through a slot, and the table of slots mg_core_load fills (mg_core_exports): the shell calls the
    core's API as if it were linked in;
  - for each name the core imports that the C library bridge does not give (host/win32/mg_crt_bridge.c), a table entry
    binding it to Megler.exe's function of that name (mg_core_host_imports): the host layer's, mg_host.h. A name no
    function of Megler.exe has fails the link here, not the load on a machine.
"""
import os
import re
import subprocess
import sys

core, arch, out = sys.argv[1], sys.argv[2], sys.argv[3]
nm = sys.argv[4] if len(sys.argv) > 4 else r'C:\Program Files\LLVM\bin\llvm-nm.exe'
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def symbols(*flags):
    text = subprocess.run([nm, '-D', *flags, core], check=True, capture_output=True, text=True).stdout
    return [line.split() for line in text.splitlines() if line.strip()]


# (Only the core's own: a library compiled into it may export its API too, libwebp's WebPDecode*, which nothing here calls.)
exports = sorted({f[-1] for f in symbols('--defined-only') if len(f) >= 3 and f[1] in ('T', 'W') and f[-1].startswith(('megler_', 'mg_'))})
imports = sorted({f[-1] for f in symbols('--undefined-only')})

bridge_src = open(os.path.join(root, 'core', 'src', 'host', 'win32', 'mg_crt_bridge.c'), encoding='utf-8').read()
table = bridge_src[bridge_src.index('const mg_core_import mg_crt_bridge_imports[]'):]
bridged = set(re.findall(r'\bE\((\w+)\)', table)) | set(re.findall(r'\bDATA\((\w+),', table)) | set(re.findall(r'\{\s*"(\w+)"', table))
host = [n for n in imports if n not in bridged]

# Every one of those is Windows' code that the core calls with Windows' convention, which it does only where its declaration
# says MG_HOSTAPI (mg_base.h): one declared without would be called with Android's on x86_64, and crash there.
declared = set()
for top in ('core/src', 'core/tests', 'core/include'):
    for d, _, files in os.walk(os.path.join(root, top)):
        for f in files:
            if f.endswith(('.h', '.c')):
                text = open(os.path.join(d, f), encoding='utf-8', errors='replace').read()
                declared |= set(re.findall(r'^MG_HOSTAPI\b[^;{(]*?\b(\w+)\s*\(', text, re.M))
undeclared = [n for n in host if n not in declared]
if undeclared:
    raise SystemExit('the core imports from Megler.exe functions no header declares with MG_HOSTAPI: ' + ', '.join(undeclared))

prefix = '_' if arch == 'x86' else ''
lines = ['/* Generated by tools/desktop-stubs.py from %s: do not edit. */' % os.path.basename(core),
         '#define MG_ELF_HOST 1',
         '#include "host/win32/mg_core_loader.h"',
         '']
# (A slot holds this until the core is loaded, or for good when it could not be: a call of the API then does nothing and
# gives 0 -- NULL, false -- rather than jumping to nowhere.)
lines.append('static long long mg_core_absent(void) { return 0; }')
for n in exports:
    lines.append('void *mg_core_slot_%s = (void *)mg_core_absent;' % n)
lines.append('')
lines.append('const mg_core_export mg_core_exports[] = {')
for n in exports:
    lines.append('    { "%s", &mg_core_slot_%s },' % (n, n))
lines.append('    { 0, 0 }')
lines.append('};')
lines.append('')
# (clang-cl reads top-level assembly as Intel's unless told; these are written as AT&T's.)
lines.append('__asm__(%s".text\\n"' % ('".att_syntax\\n" ' if arch != 'arm64' else ''))
for n in exports:
    sym, slot = prefix + n, prefix + 'mg_core_slot_' + n
    lines.append('        ".globl %s\\n"' % sym)
    if arch == 'x64':
        lines.append('        "%s:\\n    jmpq *%s(%%rip)\\n"' % (sym, slot))
    elif arch == 'x86':
        lines.append('        "%s:\\n    jmpl *%s\\n"' % (sym, slot))
    elif arch == 'arm64':
        lines.append('        "%s:\\n    adrp x16, %s\\n    ldr x16, [x16, :lo12:%s]\\n    br x16\\n"' % (sym, slot, slot))
    else:
        raise SystemExit('unknown arch ' + arch)
lines.append(');')
lines.append('')
for n in host:
    lines.append('extern void %s(void);' % n)
lines.append('')
lines.append('const mg_core_import mg_core_host_imports[] = {')
for n in host:
    lines.append('    { "%s", (void *)%s },' % (n, n))
lines.append('    { 0, 0 }')
lines.append('};')
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('%s: %d exports, %d imports (%d from the bridge, %d from the host layer)' % (os.path.basename(out), len(exports), len(imports),
                                                                                    len(imports) - len(host), len(host)))
