#!/usr/bin/env python3
"""Writes core/framework/src/megler/IR.java: the platform's resource ids, the internal ones too, as the platform's
resource table that Megler ships has them (framework-res.apk of Android 9, which tools/dvm-android-root.sh puts in the
Android root and Resources reads as the core's APK 1).

    python tools/gen-ir.py [framework-res.apk]

The numbers must be that table's: an internal resource's number differs from one Android release to the next, and a
number from another release names another resource there or none (megler.IR was once made from a newer release's
framework-res: DecorView's title frame, TabActivity's tab_content and Html's unknown_image named nothing, and
android:id/search_src_text was another resource's number).

Each type of the table is a nested class, each resource an int named as the resource with every character Java does
not take in a name ('.', '-') as '_'; the first of two that come to one name keeps it. A resource whose name is a Java
keyword (id/default) is left out, as the table's private attributes (^attr-private) are: nothing reads them by number.
The table is read with aapt2 ("dump resources") from the SDK's build-tools 29.0.3 (MEGLER_ANDROID_SDK, else the user's
Documents folder), as tools/dvm-android-root.sh cuts it.
"""
import os
import re
import subprocess
import sys

KEYWORDS = set("""abstract assert boolean break byte case catch char class const continue default do double else enum extends
final finally float for goto if implements import instanceof int interface long native new package private protected public
return short static strictfp super switch synchronized this throw throws transient try void volatile while true false null
_""".split())

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "core", "framework", "src", "megler", "IR.java")


def aapt2():
    sdk = os.environ.get("MEGLER_ANDROID_SDK") or os.path.join(os.environ.get("USERPROFILE", os.path.expanduser("~")), "Documents")
    for name in ("aapt2.exe", "aapt2"):
        p = os.path.join(sdk, "build-tools", "29.0.3", name)
        if os.path.isfile(p):
            return p
    sys.exit("no aapt2 in %s/build-tools/29.0.3 (MEGLER_ANDROID_SDK)" % sdk)


def main():
    apk = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build", "android9", "system", "framework", "framework-res.apk")
    if not os.path.isfile(apk):
        sys.exit("no %s (tools/android9-unpack.sh puts it there)" % apk)
    dump = subprocess.run([aapt2(), "dump", "resources", apk], capture_output=True, text=True, encoding="utf-8", errors="replace", check=True).stdout
    types = {}
    for m in re.finditer(r"^\s+resource 0x([0-9a-f]{8}) ([\w^-]+)/(\S+)", dump, re.M):
        value, kind, name = int(m.group(1), 16), m.group(2), m.group(3)
        if kind.startswith("^") or value >> 24 != 0x01:
            continue
        field = re.sub(r"[^A-Za-z0-9_]", "_", name)
        if field in KEYWORDS or field[0].isdigit():
            continue
        entries = types.setdefault(kind, {})
        if field not in entries:
            entries[field] = value
    if not types.get("id") or not types.get("style"):
        sys.exit("aapt2 said no ids or styles of %s" % apk)
    lines = ["// Generated by tools/gen-ir.py from the platform's resource table Megler ships (Android 9's framework-res.apk);",
             "// do not edit.", "package megler;", "", "public final class IR {"]
    for kind in sorted(types):
        lines.append("    public static final class %s {" % kind)
        for field, value in sorted(types[kind].items(), key=lambda kv: kv[1]):
            lines.append("        public static final int %s = 0x%08x;" % (field, value))
        lines.append("    }")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%s: %d types, %d resources" % (os.path.relpath(OUT, ROOT), len(types), sum(len(v) for v in types.values())))


if __name__ == "__main__":
    main()
