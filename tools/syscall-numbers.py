"""The system call numbers of Android's other ABIs as 32-bit ARM's, for core/src/bionic/mg_syscall_abi.c.

    python tools/syscall-numbers.py [ndk] > core/src/bionic/mg_syscall_abi.inc

bionic's syscall() in the core (g_syscall, core/src/bionic/mg_libc_misc.c) is written in 32-bit ARM's EABI numbers, which is
what the phone's guest code passes. Guest code of x86_64, ARM64 and x86 passes its own: BoringSSL asks for getrandom as 318 on
x86_64, 278 on ARM64, 355 on x86, 384 on ARM. This reads the numbers g_syscall handles from its source, names each by the NDK's
32-bit ARM header, and finds the call of that name -- or of the name it has there, mmap for mmap2, fstat for fstat64 -- in each
other ABI's header of the NDK (r21e): a table per ABI of {its number, ARM's}. What a call of another ABI passes differently
(a 64-bit offset in one register, mmap's offset in bytes) mg_syscall_abi.c makes ARM's by hand.
"""
import os
import re
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ndk = sys.argv[1] if len(sys.argv) > 1 else r'C:\Users\User\Documents\android-ndk-r21e'
inc = os.path.join(ndk, 'toolchains', 'llvm', 'prebuilt', 'windows-x86_64', 'sysroot', 'usr', 'include')


def read(*parts):
    return open(os.path.join(inc, *parts), encoding='utf-8').read()


def plain(text):
    """#define __NR_name N."""
    return {m.group(1): int(m.group(2)) for m in re.finditer(r'^#define __NR_(\w+)\s+(\d+)\s*$', text, re.M)}


def arm():
    text = read('arm-linux-androideabi', 'asm', 'unistd-common.h') + read('arm-linux-androideabi', 'asm', 'unistd-eabi.h')
    return {m.group(1): int(m.group(2)) for m in re.finditer(r'^#define __NR_(\w+)\s+\(__NR_SYSCALL_BASE\s*\+\s*(\d+)\)', text, re.M)}


def generic64():
    """asm-generic/unistd.h as ARM64 has it: __NR3264_ names under their 64-bit names, which the header defines first."""
    text = read('asm-generic', 'unistd.h')
    nr = plain(text)
    n3264 = {m.group(1): int(m.group(2)) for m in re.finditer(r'^#define __NR3264_(\w+)\s+(\d+)\s*$', text, re.M)}
    for m in re.finditer(r'^#define __NR_(\w+)\s+__NR3264_(\w+)\s*$', text, re.M):
        if m.group(2) in n3264:
            nr.setdefault(m.group(1), n3264[m.group(2)])
    return nr


ABIS = [
    ('MG_ARCH_X86_64', 'x86_64', plain(read('x86_64-linux-android', 'asm', 'unistd_64.h')), True),
    ('MG_ARCH_ARM64', 'arm64-v8a', generic64(), True),
    ('MG_ARCH_X86', 'x86', plain(read('i686-linux-android', 'asm', 'unistd_32.h')), False),
]
# 32-bit ARM's name -> the 64-bit ABIs' name of the same call.
LP64_NAMES = {'mmap2': 'mmap', 'stat64': 'stat', 'lstat64': 'lstat', 'fstat64': 'fstat', 'fstatat64': 'newfstatat',
              'fcntl64': 'fcntl', 'ftruncate64': 'ftruncate', 'statfs64': 'statfs', 'fstatfs64': 'fstatfs', 'ugetrlimit': 'getrlimit',
              'getuid32': 'getuid', 'getgid32': 'getgid', 'geteuid32': 'geteuid', 'getegid32': 'getegid', 'fchown32': 'fchown'}

src = open(os.path.join(root, 'core', 'src', 'bionic', 'mg_libc_misc.c'), encoding='utf-8').read()
body = src[src.index('static long g_syscall(long nr'):]
body = body[:body.index('\n}\n')]
handled = sorted({int(n) for n in re.findall(r'case (\d+):', body)})
arm_nr = arm()
arm_name = {}
for name, n in arm_nr.items():
    arm_name.setdefault(n, name)
missing = [n for n in handled if n not in arm_name]
if missing:
    raise SystemExit('g_syscall handles numbers 32-bit ARM has no name for: %s' % missing)

out = ['/* Generated by tools/syscall-numbers.py from g_syscall (mg_libc_misc.c) and NDK r21e\'s headers: do not edit. */',
       '/* {the ABI\'s number, 32-bit ARM\'s}, by the ABI\'s number; the name is ARM\'s. */']
report = []
for macro, abi, table, lp64 in ABIS:
    pairs = {}
    absent = []
    for n in handled:
        name = arm_name[n]
        theirs = LP64_NAMES.get(name, name) if lp64 else name
        if theirs not in table:
            absent.append(name)
            continue
        # (Two of ARM's for one of theirs -- fcntl and fcntl64, getuid and getuid32 on the 64-bit ABIs: the first, which
        # g_syscall handles alike.)
        pairs.setdefault(table[theirs], (n, name if theirs == name else '%s, %s here' % (name, theirs)))
    out.append('#%s %s' % ('if' if macro == ABIS[0][0] else 'elif', macro))
    out.append('static const u16 g_abi_nr[][2] = {')
    for theirs in sorted(pairs):
        n, name = pairs[theirs]
        out.append('    {%d, %d},%s/* %s */' % (theirs, n, ' ' * max(1, 12 - len('%d, %d' % (theirs, n))), name))
    out.append('};')
    report.append('%s: %d of g_syscall\'s %d calls; none of: %s' % (abi, len(pairs), len(handled), ', '.join(absent) or '-'))
out.append('#endif')
print('\n'.join(out))
for line in report:
    print(line, file=sys.stderr)
