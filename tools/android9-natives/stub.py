"""Writes the assembly source of a stub shared library: one that defines names and nothing else.

  stub.py OUT.S [--nm FILE]... [--names FILE]...

A linker needs a library to link against only to learn which names it defines
and to write its DT_NEEDED entry; what is at those names does not matter,
because at run time the names are bound by whoever loads the result (Megler's
own linker and the layer behind it). tools/android9-natives.sh links against
such stubs where no real library exists to link against:

  libopenjdkjvm.so   the runtime's own library, never built here
  libc.so, libdl.so  the NDK's stubs plus the few functions only platform code
                     may call, which the NDK's stubs leave out

--nm FILE     the output of `llvm-nm -D --defined-only` on a library whose names
              are to be repeated: "address type name" lines. T, t, W, w and i
              become functions; everything else becomes data.
--names FILE  one name per line, `#` starts a comment. A second word `object`
              makes it data (a third gives its size in bytes, 4 if absent).

Assembly, not C: a C compiler has opinions about a function called memcpy that
takes nothing and returns nothing.
"""
import sys


def main():
    args = sys.argv[1:]
    if len(args) < 3:
        raise SystemExit(__doc__)
    out_path = args[0]
    funcs, objects = {}, {}
    i = 1
    while i < len(args):
        kind, path = args[i], args[i + 1]
        i += 2
        for line in open(path, encoding='utf-8', errors='replace'):
            line = line.split('#')[0].split()
            if not line:
                continue
            if kind == '--nm':
                if len(line) < 3:
                    continue
                name, letter = line[-1].split('@')[0], line[-2]
                if letter in 'TtWwi':
                    funcs[name] = True
                else:
                    objects[name] = 4
            elif kind == '--names':
                if len(line) >= 2 and line[1] == 'object':
                    objects[line[0]] = int(line[2]) if len(line) > 2 else 4
                else:
                    funcs[line[0]] = True
            else:
                raise SystemExit('stub.py: unknown option %s' % kind)
    for name in objects:
        funcs.pop(name, None)
    out = ['@ Generated by tools/android9-natives/stub.py. Names only: nothing here is ever executed.',
           '\t.syntax unified', '\t.text', '\t.thumb']
    for name in sorted(funcs):
        out += ['\t.globl\t"%s"' % name, '\t.type\t"%s",%%function' % name, '\t.thumb_func', '"%s":' % name, '\tbx\tlr']
    out.append('\t.data')
    for name in sorted(objects):
        out += ['\t.globl\t"%s"' % name, '\t.type\t"%s",%%object' % name, '\t.size\t"%s",%d' % (name, objects[name]),
                '\t.balign\t4', '"%s":' % name, '\t.space\t%d' % objects[name]]
    open(out_path, 'w', newline='\n').write('\n'.join(out) + '\n')


main()
